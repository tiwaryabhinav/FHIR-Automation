from langgraph.types import Command

class DocVerify:

    def __init__(self):
        self.db_connect = DBConnect()
        self.graph = Graph()

    def extract_fields(self, text: str, required_fields: list[str]) -> dict:
        """This method extracts fields from text and matches which fields are present as per required fields condition"""

        extracted = {}
        missing_fields = []
        i=0
        isValid = True
        ignore_text = ["patient information","field","value", "additional_notes", "clinical information"]
        lines = [line.strip().lower() for line in text.splitlines() if line.strip()]
        required_fields = [field.strip().lower() for field in required_fields if field.strip()]

        while i < len(lines):
            line = lines[i]
            
            #Name
            #Abhinav
            if line.strip() in required_fields:
                field = line
                value = ""
                if i+1 < len(lines):
                    next_line = lines[i+1]
                    if next_line not in ignore_text and next_line not in required_fields:
                        value = next_line.strip()
                extracted[field] = value
                i = i+2
                continue
            i = i+1

        for field in required_fields:
            if not extracted.get(field, "").strip():
                missing_fields.append(field)
                isValid = False

        return {
            "isValid" : isValid,
            "missing_fields" : missing_fields
        }

    async def verify_doc(self, patientId: str, reviewId:str, file: UploadFile = File(...)):

        if not patientId.strip():
            raise Exception({
                "STATUS_CODE" : "400",
                "MESSAGE" : "INVALID PATIENT ID"
            })

        #file can a pdf or text or image.
        #in pdf it can be scanned too.
        text = ""
        pdf_bytes = await file.read()
        reader = PdfReader(BytesIO(pdf_bytes))
        for index,page in enumerate(reader.pages):
            page_text = page.extract_text()
            #print(index,' - ',page_text)
            if page_text:
                text += page_text + "\n"

        if not text:
            raise Exception("Invalid file Uploaded")
        
        #Extract needed fields from PostGres DB
        required_fields = await self.db_connect.get_required_fields()

        #need to see if text contains all required fields
        extracted_fields_response = self.extract_fields(text, required_fields)

        if not (extracted_fields_response and extracted_fields_response.get("isValid")):

            #need to send this to an LLM and draft a summary for this.
            state = State(messages=[],
                        summary="",
                        missing_fields=extracted_fields_response.get("missing_fields",[]),
                        patientId=patientId,
                        intent="",
                        preceding_team="CareFlow",
                        reviewId=reviewId
            )
            response = await self.graph.compiled_graph.ainvoke(state, config={"configurable" : {"thread_id" : reviewId}})
            interrupts = response.get("__interrupt__", [])

            # LangGraph returns Interrupt instances, not dictionaries.
            if interrupts:
                return interrupts[0].value

            return response

        return {
            "isValid": True,
            "message": "All required fields are present",
        }

    async def approve_summary(self, reviewId: str, decision: str, summary: str | None = None):
        """This method is responsible for approving/rejecting the summary generated by LLM"""
        decision = decision.strip().lower()
        if decision not in {"yes", "no"}:
            raise HTTPException(
                status_code=422,
                detail="decision must be 'yes' or 'no'",
            )
        
        edited_summary = summary.strip() if summary and summary.strip() else None
        if decision == "no" and edited_summary is None:
            raise HTTPException(
                status_code=400,
                detail="Provide an updated summary when rejecting the current one",
            )

        resume_value = {"decision": decision}
        if edited_summary is not None:
            resume_value["summary"] = edited_summary

        return await self.graph.compiled_graph.ainvoke(
            Command(resume=resume_value),
            config={"configurable": {"thread_id": reviewId}},
        )

