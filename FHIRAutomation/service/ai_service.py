
from typing import Literal
from dotenv import load_dotenv
from langchain_core.messages import HumanMessage, SystemMessage
from langgraph.graph import StateGraph, START, END
from configurations.llm_config import State, llm
from langgraph.types import Interrupt, Command, interrupt
from langgraph.checkpoint.memory import InMemorySaver

class Graph:

    def __init__(self) -> None:
        load_dotenv()
        #build graph
        self.graph_builder = StateGraph(State)

        #add nodes
        self.graph_builder.add_node("intent_detect_node", self.intent_detect_node)
        self.graph_builder.add_node("missing_fields_summary_node", self.missing_field_summary_node)
        self.graph_builder.add_node("human_review_node", self.human_review_node)
        self.graph_builder.add_node("send_message_node", self.send_message_node)
        self.graph_builder.add_node("unrelated_node", self.unrelated_node)
        self.graph_builder.add_node("undo_summary_node", self.undo_summary_node)

        #add edges
        self.graph_builder.add_edge(START, "intent_detect_node")
        self.graph_builder.add_conditional_edges("intent_detect_node", self.route_by_intent)
        self.graph_builder.add_edge("missing_fields_summary_node", "human_review_node")
        self.graph_builder.add_edge("send_message_node", END)
        self.graph_builder.add_edge("unrelated_node", END)
        self.graph_builder.add_edge("undo_summary_node", END)

        #compile the graph
        self.compiled_graph = self.graph_builder.compile(checkpointer=InMemorySaver())

    def intent_detect_node(self, old_state: State):
        """This is responsible to detect intent of incoming request."""

        intent = "UNRELATED"
        missing_fields = old_state.get("missing_fields")
        if missing_fields:
            intent = "FIELD_MISSING"

        return {
            "intent" : intent
        }

    def unrelated_node(self, old_state: State):
        """This method is responsible for handing unrelated intent"""

        print("Unrelated node")
        return {
            "summary" : "Unrelated information"
        }

    def undo_summary_node(self, old_state: State):
        """This method is invoked when user rejects summary generated by LLM"""

        print("inside undo summart node")
        return {
            "user_decision" : "no"
        }


    def missing_field_summary_node(self, old_state: State):
        """This method is responsible to generating summary for missing fields"""

        missing_fields = old_state.get("missing_fields")

        system_prompt = f"""You are a summary generator that generates a summary for missing fields in a document.
        Write a brief summary mentioning that some fields are missing and that needs to be included for patientId {old_state.get("patientId")}
        Missing fields are: {missing_fields}.
        Do not invent fields yourself. Use only from the provided missing fields.
        """

        response = llm.invoke([SystemMessage(content=system_prompt), HumanMessage(content="Generate a summary for provided missing fields.")])

        print("LLM response - ",response)
        return {
            "summary" : response.content
        }

    def route_by_intent(self, old_state: State) -> Literal["missing_fields_summary_node", "unrelated_node"]:
        """This method is used to detect intent of incoming request"""

        intent = old_state.get("intent")

        if intent == "FIELD_MISSING":
            return "missing_fields_summary_node"
        return "unrelated_node"

    def send_message_node(self, old_state: State):

        summary = old_state.get("summary", "")

        print("Inside send message node")
        print(old_state.get("preceding_team"),' - ',summary)
        return {
            "user_decision" : "yes"
        }

    def human_review_node(self, old_state: State) -> Command:
        """This method is used to pause the execution flow and wait for human approval of generated summary"""


        review = interrupt({
            "question" : "Is this summary good to be send?",
            "summary" : old_state.get("summary",""),
            "reviewId" : old_state.get("reviewId","")
        })

        decision = review.get("decision", "").strip().lower()
        submitted_summary = review.get("summary", "")

        if decision == "yes":
            return Command(
                update={
                    "summary": old_state.get("summary", ""),
                    "review_status": "approved",
                },
                goto="send_message_node")
        return Command(
            update={"summary": submitted_summary, "review_status": "rejected"},
            goto="undo_summary_node")
        

        
        
